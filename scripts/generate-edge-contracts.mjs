#!/usr/bin/env node
import { createHash } from "node:crypto";
import { readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";

const root = resolve(import.meta.dirname, "..");
const schemaPath = resolve(root, "contracts/edge/v2/schema.json");
const outputPath = resolve(root, "crates/surface/src/edge_v2_generated.rs");
const schemaBytes = readFileSync(schemaPath);
const schema = JSON.parse(schemaBytes);
const hash = createHash("sha256").update(schemaBytes).digest("hex");
if (schema.protocol !== "cowd.edge.v2") throw new Error("unexpected Edge protocol");
for (const name of ["EdgeBootstrapRequest", "EdgeBootstrapResponse", "EdgeEventEnvelope", "EdgeEventAck", "ManagedRuntime"]) {
  if (!schema.definitions[name]) throw new Error(`missing definition ${name}`);
}

const generated = `// @generated by scripts/generate-edge-contracts.mjs; do not edit.\n` +
`// schema-sha256: ${hash}\n` +
`pub const EDGE_PROTOCOL_V2: &str = "${schema.protocol}";\n\n` +
`#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]\n` +
`pub struct EdgeBootstrapRequest {\n    pub protocol: String,\n    pub gateway_version: String,\n    pub surface_id: String,\n    pub driver_profile: String,\n    #[serde(default)]\n    pub capabilities: Vec<String>,\n}\n\n` +
`#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]\n` +
`pub struct EdgeBootstrapResponse {\n    pub protocol: String,\n    pub surface_id: String,\n    pub driver_profile: String,\n    pub capabilities: Vec<String>,\n    pub max_in_flight: usize,\n}\n\n` +
`#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]\n` +
`pub struct EdgeEventEnvelope {\n    pub sequence: u64,\n    pub frame: SurfaceFrame,\n}\n\n` +
`#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]\n` +
`pub struct EdgeEventAck {\n    pub sequence: u64,\n}\n`;

if (process.argv.includes("--check")) {
  const current = readFileSync(outputPath, "utf8");
  if (current !== generated) throw new Error("generated Edge v2 contract is stale");
  console.log(`edge v2 contract gate passed (${hash})`);
} else {
  writeFileSync(outputPath, generated);
  console.log(`generated Edge v2 contract (${hash})`);
}
